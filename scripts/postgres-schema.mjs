// Writes prisma/postgres.prisma: prisma/schema.prisma (SQLite, used for local dev) switched to
// PostgreSQL for production. Run before `prisma generate --schema prisma/postgres.prisma`.
//
// Production runs on Netlify Database, which injects NETLIFY_DB_URL into functions at runtime
// (the name @netlify/database reads; it is not listed by `netlify env:list`).
// DATABASE_URL wins when it holds a postgres:// URL (another provider, or a local Postgres).
// Generating the client needs no connection, so the variable may be unset at build time.
// Tables are created by the SQL migrations in netlify/database/migrations, applied on deploy.
import { writeFileSync, readFileSync } from "node:fs";

const isPostgres = (name) => /^postgres(ql)?:\/\//.test(process.env[name] ?? "");
const url = isPostgres("DATABASE_URL") ? "DATABASE_URL" : "NETLIFY_DB_URL";

const source = readFileSync("prisma/schema.prisma", "utf8");
const datasource = `datasource db {
  provider = "postgresql"
  url      = env("${url}")
}`;
const out = source.replace(/datasource db \{[^}]*\}/, datasource);
if (out === source) {
  console.error("postgres-schema: no datasource block found in prisma/schema.prisma");
  process.exit(1);
}

writeFileSync("prisma/postgres.prisma", `// GENERATED by scripts/postgres-schema.mjs from schema.prisma. Do not edit.\n${out}`);
console.log(`postgres-schema: prisma/postgres.prisma written (url=${url})`);
