// Writes prisma/postgres.prisma: prisma/schema.prisma (SQLite, used for local dev) switched to
// PostgreSQL for production. Run before `prisma generate --schema prisma/postgres.prisma`.
//
// The connection string comes from the first of these env vars that is set:
//   DATABASE_URL (when it starts with postgres), NETLIFY_DATABASE_URL (Netlify DB / Neon)
// and the direct (non-pooled) one, used by `prisma db push`, from:
//   DIRECT_URL, NETLIFY_DATABASE_URL_UNPOOLED
import { readFileSync, writeFileSync } from "node:fs";

const isPostgres = (name) => /^postgres(ql)?:\/\//.test(process.env[name] ?? "");
const url = ["DATABASE_URL", "NETLIFY_DATABASE_URL"].find(isPostgres);
const direct = ["DIRECT_URL", "NETLIFY_DATABASE_URL_UNPOOLED"].find(isPostgres);

if (!url) {
  console.error("postgres-schema: set DATABASE_URL (or NETLIFY_DATABASE_URL) to a postgres:// connection string");
  process.exit(1);
}

const source = readFileSync("prisma/schema.prisma", "utf8");
const datasource = `datasource db {
  provider = "postgresql"
  url      = env("${url}")${direct ? `\n  directUrl = env("${direct}")` : ""}
}`;
const out = source.replace(/datasource db \{[^}]*\}/, datasource);
if (out === source) {
  console.error("postgres-schema: no datasource block found in prisma/schema.prisma");
  process.exit(1);
}

writeFileSync("prisma/postgres.prisma", `// GENERATED by scripts/postgres-schema.mjs from schema.prisma. Do not edit.\n${out}`);
console.log(`postgres-schema: prisma/postgres.prisma written (url=${url}${direct ? `, directUrl=${direct}` : ""})`);
